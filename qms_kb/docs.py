@dataclass
class Chunk:
    chunk_id: str
    doc_id: str
    version: str
    status: str
    level: str
    title: str
    heading: str
    text: str
    effective_date: str

    def cite(self) -> str:
        return f"{self.doc_id} v{self.version} §{self.heading.split()[0]}"


def chunk_docs(docs=DOCS):
    """按章节切分：一个章节一块，并带上文档元数据（版本、状态、密级、生效日期）。"""
    out = []
    for d in docs:
        for heading, text in d.sections:
            cid = f"{d.doc_id}@{d.version}#{heading.split()[0]}"
            out.append(Chunk(cid, d.doc_id, d.version, d.status, d.level,
                             d.title, heading, text, d.effective_date))
    return out
